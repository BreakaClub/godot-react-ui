// Bundles src/bench.ts for GodotJS the way scripts/build.mjs bundles the demo (esbuild, CommonJS, `godot` modules external), into
// this project's own `.godot/GodotJS/src`. The CodeMirror packages come from ../cm/node_modules, @tanstack/virtual-core from
// ../frameworks/virtual/node_modules (see their package.json files; `npm install --legacy-peer-deps --ignore-scripts`).
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const here = import.meta.dirname;
const root = resolve(here, '../../..');
// The sample document: two whole lab-sized files, so every construct in it parses.
const text = ['demo/src/filters-lab.tsx', 'src/kit/select.tsx'].map((file) => readFileSync(resolve(root, file), 'utf8')).join('\n');
writeFileSync(resolve(here, 'src/sample.ts'), `// Generated by build.mjs: demo/src/filters-lab.tsx then src/kit/select.tsx.\nexport const SAMPLE_TEXT = ${JSON.stringify(text)};\n`);
await build({
  absWorkingDir: root, bundle: true, platform: 'neutral', target: 'es2022', sourcemap: true, format: 'cjs',
  mainFields: ['module', 'main'], conditions: ['import', 'module', 'default'],
  nodePaths: [resolve(here, '../cm/node_modules'), resolve(here, '../frameworks/virtual/node_modules')],
  external: ['godot', 'godot.lib.api', 'godot.annotations', 'godot-jsb'],
  define: { 'process.env.NODE_ENV': '"production"' },
  entryPoints: [resolve(here, 'src/bench.ts')], outdir: resolve(here, '.godot/GodotJS/src'),
});
console.log('built', resolve(here, '.godot/GodotJS/src/bench.js'));
